// Builds a standalone index.html from the Claude Design canvas source.
//   node scripts/build.mjs
// Source of truth: design/project/Main.dc.html (edit that, or re-export from the canvas).
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const src = readFileSync(join(root, 'design/project/Main.dc.html'), 'utf8');

const between = (s, a, b) => {
  const i = s.indexOf(a);
  const j = s.indexOf(b, i + a.length);
  if (i < 0 || j < 0) throw new Error('Could not find ' + a + ' … ' + b + ' in Main.dc.html');
  return s.slice(i + a.length, j);
};

const title = (src.match(/<title>([\s\S]*?)<\/title>/) || [, 'Unlocked'])[1].trim();
const helmet = between(src, '<helmet>', '</helmet>').trim();
const template = between(src, '</helmet>', '</x-dc>').trim();
const scriptOpen = src.indexOf('data-dc-script');
const script = between(src.slice(src.indexOf('>', scriptOpen) - 1), '>', '</script>').trim();

const html = `<!doctype html>
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<title>${title}</title>
<!-- Generated by scripts/build.mjs from design/project/Main.dc.html. Do not edit by hand. -->
${helmet}
<style>sc-if,sc-for{display:contents}</style>
</head>
<body>
<div id="app"></div>
<template id="dc-template">
${template}
</template>
<script src="runtime/dc-runtime.js"></script>
<script>
${script}
</script>
<script>
DCRuntime.mount(Component, document.getElementById('dc-template'), document.getElementById('app'));
</script>
</body>
</html>
`;

writeFileSync(join(root, 'index.html'), html);
console.log('Wrote index.html (' + Math.round(html.length / 1024) + ' KB)');
